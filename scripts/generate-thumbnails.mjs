import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';

const ROOT = process.cwd();
const GAMES_PATH = path.join(ROOT, 'public/assets/games.json');
const CURATED_DIR = path.join(ROOT, 'public/assets/thumbnails/curated');
const AUTO_DIR = path.join(ROOT, 'public/assets/thumbnails/auto');
await fs.mkdir(AUTO_DIR, { recursive: true });

const games = JSON.parse(await fs.readFile(GAMES_PATH, 'utf8'));
const palette = ['#00e5ff','#7c3aed','#22c55e','#f59e0b','#ef4444'];
let curatedUsed = 0, autoGenerated = 0;

function colorFor(id) {
  const h = crypto.createHash('md5').update(id).digest('hex');
  return palette[parseInt(h.slice(0,8),16) % palette.length];
}

for (const g of games) {
  const thumb = String(g.thumbnail || '');
  const needsFix = !thumb || thumb.includes('/generated/') || thumb.includes('placeholder');
  if (!needsFix) continue;

  const curatedFile = path.join(CURATED_DIR, `${g.id}.webp`);
  try {
    await fs.access(curatedFile);
    g.thumbnail = `/assets/thumbnails/curated/${g.id}.webp`;
    curatedUsed++;
    continue;
  } catch {}

  const color = colorFor(g.id);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="200"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#0b0f14"/><stop offset="1" stop-color="#101827"/></linearGradient></defs><rect width="100%" height="100%" rx="18" fill="url(#g)"/><circle cx="252" cy="42" r="52" fill="${color}" opacity=".16"/><path d="M105 134c15-40 43-66 79-76 24 30 33 63 26 100-41 14-76 6-105-24z" fill="${color}" opacity=".86"/></svg>`;
  const out = path.join(AUTO_DIR, `${g.id}.webp`);
  await sharp(Buffer.from(svg)).webp({ quality: 85 }).toFile(out);
  g.thumbnail = `/assets/thumbnails/auto/${g.id}.webp`;
  autoGenerated++;
}

await fs.writeFile(GAMES_PATH, JSON.stringify(games, null, 2) + '\n');
console.log(JSON.stringify({ scanned: games.length, curatedUsed, autoGenerated }, null, 2));
